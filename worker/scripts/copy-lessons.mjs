// Bundles the lesson files into the Worker before each build, so the
// server has its own copy: prompts are built from the lesson on the
// server, never from text the app sends.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const from = join(here, "..", "..", "content", "lessons");
const to = join(here, "..", "src", "generated");

const files = readdirSync(from).filter((f) => f.endsWith(".json")).sort();
const lessons = files.map((f) => JSON.parse(readFileSync(join(from, f), "utf8")));
mkdirSync(to, { recursive: true });
writeFileSync(
  join(to, "lessons.ts"),
  "// Generated by scripts/copy-lessons.mjs from content/lessons/. Don't edit.\n" +
    `export const LESSONS: unknown[] = ${JSON.stringify(lessons)};\n`,
);
console.log(`Bundled ${files.length} lessons into worker/src/generated/lessons.ts`);
